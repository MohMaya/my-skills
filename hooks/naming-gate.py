#!/usr/bin/env python3
"""Reject new names that carry no information.

The gate reads added lines only, so existing code is never renamed by surprise.
Comments and string literals are blanked before matching, so a banned word in
prose or a message is not a finding. It enforces the objective subset of the
naming skill; every judgment call stays with the reviewer.

Parsed declarations: variables, functions, and parameters in TypeScript,
JavaScript, Python, Go, Rust, and Swift, plus `self`/`this` attribute assignment
in TypeScript and Python. Struct fields, object-literal properties, and
class-body annotations are not parsed; the reviewer covers them.

  naming-gate.py              changed files in this repository
  naming-gate.py PATH...      added lines in these paths
  naming-gate.py --whole PATH every line, for a file outside git

A line carrying `naming: ignore` in a comment is skipped.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from collections.abc import Iterator
from dataclasses import dataclass
from pathlib import Path

VACUOUS = frozenset(
    {
        "data", "info", "obj", "object", "val", "tmp", "temp", "thing",
        "stuff", "misc", "foo", "bar", "baz", "qux", "dummy",
    }
)  # fmt: skip
NOISE_SUFFIX = frozenset({"data", "info", "object", "manager", "helper", "util", "utils"})
VAGUE_VERB = frozenset({"handle", "process", "manage", "do", "perform"})
GENERIC_OBJECT = frozenset(
    {
        "data", "info", "stuff", "thing", "things", "item", "items", "object",
        "objects", "value", "values", "result", "results",
    }
)  # fmt: skip
KEYWORDS = frozenset(
    {
        "if", "for", "while", "switch", "catch", "return", "new", "function",
        "else", "do", "try", "with", "when", "guard", "match", "loop", "await",
        "typeof", "sizeof", "delete", "throw", "in", "of", "and", "or", "not",
        "self", "cls", "this", "default",
    }
)  # fmt: skip
SKIP_DIRS = frozenset(
    {"node_modules", "dist", "build", ".venv", "venv", "target", "vendor", ".git"}
)
GENERATED = ("@generated", "code generated by", "do not edit")
IGNORE = re.compile(r"naming:\s*ignore", re.IGNORECASE)

WORD = re.compile(r"[A-Z]+(?=[A-Z][a-z])|[A-Z]?[a-z]+|[A-Z]+|\d+")
HUNK = re.compile(r"^@@ -\d+(?:,\d+)? \+(\d+)(?:,\d+)? @@")

TS_VAR = re.compile(r"\b(?:const|let|var)\s+([A-Za-z_$][\w$]*)")
TS_TYPE = re.compile(r"\b(?:class|interface|type|enum)\s+([A-Za-z_$][\w$]*)")
TS_FUNC = re.compile(
    r"\bfunction\s+([A-Za-z_$][\w$]*)\s*(?:<[^>]*>)?\s*\(([^)]*)\)"
)
TS_ARROW = re.compile(
    r"\b(?:const|let|var)\s+([A-Za-z_$][\w$]*)\s*=\s*(?:async\s*)?"
    r"(?:<[^>]*>\s*)?\(([^)]*)\)"
)
TS_METHOD = re.compile(
    r"^\s*(?:(?:public|private|protected|static|async|readonly|override|abstract)\s+)*"
    r"([A-Za-z_$][\w$]*)\s*(?:<[^>]*>)?\s*\(([^)]*)\)\s*(?::\s*[^{]+)?\{"
)
TS_FIELD = re.compile(
    r"^\s+(?:(?:public|private|protected|static|readonly|declare|override)\s+)+"
    r"([A-Za-z_$][\w$]*)\s*[?!]?\s*[:=]"
)
TS_THIS = re.compile(r"\bthis\.([A-Za-z_$][\w$]*)\s*(?::[^=]+)?=(?!=)")

PY_DEF = re.compile(r"^\s*(?:async\s+)?def\s+([A-Za-z_]\w*)\s*\(")
PY_PARAMS = re.compile(r"^\s*(?:async\s+)?def\s+[A-Za-z_]\w*\s*\(([^)]*)\)")
PY_CLASS = re.compile(r"^\s*class\s+([A-Za-z_]\w*)")
PY_ASSIGN = re.compile(r"^\s*([A-Za-z_]\w*)\s*(?::\s*[^=]+)?=(?!=)")
PY_ATTR = re.compile(r"\b(?:self|cls)\.([A-Za-z_]\w*)\s*(?::[^=]+)?=(?!=)")
PY_LOOP = re.compile(r"\bfor\s+(.+?)\s+in\b")

GO_FUNC = re.compile(
    r"\bfunc\s+(?:\([^)]*\)\s*)?([A-Za-z_]\w*)\s*(?:\[[^\]]*\])?\s*\(([^)]*)\)"
)
GO_TYPE = re.compile(r"\btype\s+([A-Za-z_]\w*)")
GO_VAR = re.compile(r"\bvar\s+([A-Za-z_]\w*)")
GO_ASSIGN = re.compile(r"^\s*(?:(?:if|for|switch)\s+)?([A-Za-z_][\w, ]*?)\s*:=")

RS_LET = re.compile(r"\blet\s+(?:mut\s+)?([A-Za-z_]\w*)")
RS_FN = re.compile(r"\bfn\s+([A-Za-z_]\w*)\s*(?:<[^>]*>)?\s*\(([^)]*)\)")
RS_TYPE = re.compile(r"\b(?:struct|enum|trait|union)\s+([A-Za-z_]\w*)")

SWIFT_LET = re.compile(r"\b(?:let|var)\s+([A-Za-z_]\w*)")
SWIFT_FUNC = re.compile(r"\bfunc\s+([A-Za-z_]\w*)\s*(?:<[^>]*>)?\s*\(([^)]*)\)")
SWIFT_TYPE = re.compile(r"\b(?:class|struct|enum|protocol|actor)\s+([A-Za-z_]\w*)")

RS_RAW = re.compile(r'r(#*)"')
SWIFT_RAW = re.compile(r'(#+)"')
CHAR = re.compile(r"'(?:\\.|[^'\\])'")


@dataclass(frozen=True)
class Dialect:
    line_comment: str
    block: tuple[str, str] | None
    quotes: tuple[str, ...]
    multiline: tuple[str, ...]
    raw: re.Pattern[str] | None = None
    char: re.Pattern[str] | None = None
    no_escape: tuple[str, ...] = ()


@dataclass(frozen=True)
class Open:
    closer: str
    multiline: bool
    escapes: bool = False
    comment: bool = False


DIALECTS = {
    "ts": Dialect("//", ("/*", "*/"), ('"', "'", "`"), ("`",)),
    "python": Dialect("#", None, ('"""', "'''", '"', "'"), ('"""', "'''")),
    "go": Dialect("//", ("/*", "*/"), ('"', "`"), ("`",), char=CHAR, no_escape=("`",)),
    "rust": Dialect("//", ("/*", "*/"), ('"',), ('"',), RS_RAW, CHAR),
    "swift": Dialect("//", ("/*", "*/"), ('"""', '"'), ('"""',), SWIFT_RAW),
}

EXTENSIONS = {
    ".ts": "ts", ".tsx": "ts", ".mts": "ts", ".cts": "ts",
    ".js": "ts", ".jsx": "ts", ".mjs": "ts", ".cjs": "ts",
    ".py": "python", ".pyi": "python",
    ".go": "go", ".rs": "rust", ".swift": "swift",
}  # fmt: skip


@dataclass(frozen=True)
class Name:
    kind: str
    text: str
    line: int


def words(name: str) -> list[str]:
    return [
        word.lower()
        for part in re.split(r"[^A-Za-z0-9]+", name)
        for word in WORD.findall(part)
    ]


def blank(chars: list[str], start: int, stop: int) -> None:
    for index in range(start, min(stop, len(chars))):
        chars[index] = " "


def escaped(raw: str, index: int) -> bool:
    run = 0
    while index - run - 1 >= 0 and raw[index - run - 1] == "\\":
        run += 1
    return run % 2 == 1


def closing(raw: str, delimiter: str, start: int, escapes: bool) -> int:
    end = raw.find(delimiter, start)
    while escapes and end >= 0 and escaped(raw, end):
        end = raw.find(delimiter, end + 1)
    return end


def consume(
    raw: str, chars: list[str], index: int, state: Open
) -> tuple[int, Open | None]:
    """Blank the open construct from index and return where code resumes."""
    end = closing(raw, state.closer, index, state.escapes)
    if end < 0:
        blank(chars, index, len(chars))
        return len(chars), state if state.multiline else None
    blank(chars, index, end + len(state.closer))
    return end + len(state.closer), None


def opening(raw: str, index: int, dialect: Dialect) -> tuple[Open, int] | None:
    if dialect.raw:
        match = dialect.raw.match(raw, index)
        if match:
            return Open('"' + match.group(1), True), match.end() - index
    quote = next((q for q in dialect.quotes if raw.startswith(q, index)), None)
    if quote is None:
        return None
    escapes = quote not in dialect.no_escape
    return Open(quote, quote in dialect.multiline, escapes), len(quote)


def strip(raw: str, dialect: Dialect, state: Open | None) -> tuple[str, Open | None, int]:
    """Blank comments, literals and strings, keeping offsets and open state."""
    chars = list(raw)
    index = 0
    comment = 0 if state is not None and state.comment else len(raw)
    while index < len(chars):
        if state is not None:
            index, state = consume(raw, chars, index, state)
            continue
        if raw.startswith(dialect.line_comment, index):
            comment = min(comment, index)
            blank(chars, index, len(chars))
            break
        if dialect.char:
            literal = dialect.char.match(raw, index)
            if literal:
                blank(chars, index, literal.end())
                index = literal.end()
                continue
        if dialect.block and raw.startswith(dialect.block[0], index):
            comment = min(comment, index)
            state = Open(dialect.block[1], True, comment=True)
            index += len(dialect.block[0])
            continue
        found = opening(raw, index, dialect)
        if found:
            state, width = found
            index += width
            continue
        index += 1
    return "".join(chars), state, comment


def ignored(line: str, comment: int) -> bool:
    return IGNORE.search(line, comment) is not None


def params(text: str) -> Iterator[str]:
    for part in text.split(","):
        match = re.match(
            r"\s*(?:@\w+\s+)*(?:\.\.\.)?(?:mut\s+)?(?:_\s+)?(?:const\s+)?"
            r"([A-Za-z_$][\w$]*)",
            part,
        )
        if match and match.group(1) not in KEYWORDS:
            yield match.group(1)


def targets(text: str) -> Iterator[str]:
    for part in text.split(","):
        name = part.strip().strip("()[]")
        if re.fullmatch(r"[A-Za-z_]\w*", name):
            yield name


def ts_names(line: str) -> Iterator[tuple[str, str]]:
    for pattern, kind in (
        (TS_VAR, "variable"),
        (TS_TYPE, "type"),
        (TS_THIS, "variable"),
        (TS_FIELD, "variable"),
    ):
        for match in pattern.finditer(line):
            yield kind, match.group(1)
    for pattern in (TS_FUNC, TS_ARROW):
        for match in pattern.finditer(line):
            yield "function", match.group(1)
            for name in params(match.group(2)):
                yield "parameter", name
    match = TS_METHOD.match(line)
    if match and match.group(1) not in KEYWORDS:
        yield "function", match.group(1)
        for name in params(match.group(2)):
            yield "parameter", name


def python_names(line: str) -> Iterator[tuple[str, str]]:
    for pattern, kind in ((PY_DEF, "function"), (PY_CLASS, "type"), (PY_ATTR, "variable")):
        for match in pattern.finditer(line):
            yield kind, match.group(1)
    match = PY_PARAMS.match(line)
    if match:
        for name in params(match.group(1)):
            yield "parameter", name
    match = PY_ASSIGN.match(line)
    if match:
        yield "variable", match.group(1)
    for match in PY_LOOP.finditer(line):
        for name in targets(match.group(1)):
            yield "variable", name


def go_names(line: str) -> Iterator[tuple[str, str]]:
    for pattern, kind in ((GO_FUNC, "function"), (GO_TYPE, "type"), (GO_VAR, "variable")):
        for match in pattern.finditer(line):
            yield kind, match.group(1)
    match = GO_FUNC.search(line)
    if match:
        for name in params(match.group(2)):
            yield "parameter", name
    match = GO_ASSIGN.match(line)
    if match:
        for name in targets(match.group(1)):
            yield "variable", name


def rust_names(line: str) -> Iterator[tuple[str, str]]:
    for pattern, kind in ((RS_LET, "variable"), (RS_FN, "function"), (RS_TYPE, "type")):
        for match in pattern.finditer(line):
            yield kind, match.group(1)
    match = RS_FN.search(line)
    if match:
        for name in params(match.group(2)):
            yield "parameter", name


def swift_names(line: str) -> Iterator[tuple[str, str]]:
    for pattern, kind in (
        (SWIFT_LET, "variable"),
        (SWIFT_FUNC, "function"),
        (SWIFT_TYPE, "type"),
    ):
        for match in pattern.finditer(line):
            yield kind, match.group(1)
    match = SWIFT_FUNC.search(line)
    if match:
        for name in params(match.group(2)):
            yield "parameter", name


NAMERS = {
    "ts": ts_names,
    "python": python_names,
    "go": go_names,
    "rust": rust_names,
    "swift": swift_names,
}


def declared(line: str, language: str, number: int) -> Iterator[Name]:
    for kind, text in NAMERS[language](line):
        yield Name(kind, text, number)


def why(name: Name) -> str | None:
    parts = words(name.text)
    joined = "".join(parts)
    if joined in VACUOUS:
        return "is vacuous; name the role"
    if name.kind == "type" and parts and parts[-1] in NOISE_SUFFIX:
        return "carries a noise suffix; name the concept"
    if (
        name.kind == "function"
        and len(parts) > 1
        and parts[0] in VAGUE_VERB
        and parts[-1] in GENERIC_OBJECT
    ):
        return "pairs a vague verb with a generic object; name the job"
    return None


def findings(line: str, language: str, number: int) -> Iterator[tuple[Name, str]]:
    seen: set[tuple[str, str]] = set()
    for name in declared(line, language, number):
        reason = why(name)
        if reason and (name.text, name.kind) not in seen:
            seen.add((name.text, name.kind))
            yield name, reason


def git(root: Path, *args: str) -> str:
    try:
        result = subprocess.run(
            ["git", *args], cwd=root, capture_output=True, text=True, timeout=15
        )
    except (subprocess.SubprocessError, OSError):
        return ""
    return result.stdout if result.returncode == 0 else ""


def generated(path: Path) -> bool:
    try:
        head = path.read_text(errors="ignore")[:2048].lower()
    except OSError:
        return True
    return any(marker in head for marker in GENERATED)


def inside(path: Path, root: Path) -> str | None:
    try:
        return str(path.resolve().relative_to(root))
    except ValueError:
        return None


def wanted(path: Path, root: Path) -> bool:
    if EXTENSIONS.get(path.suffix.lower()) is None or generated(path):
        return False
    relative = inside(path, root)
    if relative is None:
        return True
    return not any(part in SKIP_DIRS for part in Path(relative).parts)


def git_paths(root: Path, *args: str) -> list[str]:
    try:
        result = subprocess.run(
            ["git", *args, "-z"], cwd=root, capture_output=True, text=True, timeout=15
        )
    except (subprocess.SubprocessError, OSError):
        return []
    return [p for p in result.stdout.split("\0") if p] if result.returncode == 0 else []


def changed_paths(root: Path) -> list[Path]:
    names = (
        git_paths(root, "diff", "--name-only", "--diff-filter=d")
        + git_paths(root, "diff", "--cached", "--name-only", "--diff-filter=d")
        + git_paths(root, "ls-files", "--others", "--exclude-standard")
    )
    return sorted({root / name for name in names})


def tracked(root: Path, relative: str) -> bool:
    return bool(git(root, "ls-files", "--", relative).strip())


def committed(root: Path) -> bool:
    return bool(git(root, "rev-parse", "--verify", "--quiet", "HEAD").strip())


def whole_lines(path: Path) -> list[tuple[int, str]]:
    try:
        return list(enumerate(path.read_text(errors="ignore").splitlines(), 1))
    except OSError:
        return []


def diff_lines(root: Path, relative: str) -> list[tuple[int, str]]:
    if not tracked(root, relative) or not committed(root):
        return whole_lines(root / relative)
    return added(git(root, "diff", "-U0", "HEAD", "--", relative))


def added(diff: str) -> list[tuple[int, str]]:
    number = 0
    in_hunk = False
    found: list[tuple[int, str]] = []
    for raw in diff.splitlines():
        hunk = HUNK.match(raw)
        if hunk:
            in_hunk = True
            number = int(hunk.group(1))
            continue
        if not in_hunk:
            continue
        if raw.startswith("+"):
            found.append((number, raw[1:]))
            number += 1
        elif not raw.startswith("-") and not raw.startswith("\\"):
            number += 1
    return found


def report(path: str, line: str, language: str, number: int) -> list[str]:
    return [
        f"{path}:{name.line} `{name.text}` {reason}"
        for name, reason in findings(line, language, number)
    ]


def rows_for(
    root: Path, path: Path, relative: str | None, whole: bool
) -> list[tuple[int, str]]:
    if whole or not relative:
        return whole_lines(path)
    return diff_lines(root, relative)


def open_states(path: Path, dialect: Dialect) -> dict[int, Open | None]:
    """The construct open at the start of each line, so a hunk starts in context."""
    state: Open | None = None
    table: dict[int, Open | None] = {}
    for number, line in whole_lines(path):
        table[number] = state
        _, state, _ = strip(line, dialect, state)
    return table


def check(root: Path, paths: list[Path], whole: bool) -> list[str]:
    found: list[str] = []
    for path in paths:
        if not wanted(path, root):
            continue
        relative = inside(path, root)
        language = EXTENSIONS[path.suffix.lower()]
        dialect = DIALECTS[language]
        table = open_states(path, dialect)
        for number, line in rows_for(root, path, relative, whole):
            code, _, comment = strip(line, dialect, table.get(number))
            if ignored(line, comment):
                continue
            found += report(relative or str(path), code, language, number)
    return found


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(prog="naming-gate.py")
    parser.add_argument("paths", nargs="*")
    parser.add_argument("--whole", action="store_true", help="check every line")
    args = parser.parse_args(argv)
    top = git(Path.cwd(), "rev-parse", "--show-toplevel").strip()
    root = Path(top or Path.cwd()).resolve()
    if args.paths:
        paths = [Path(path).resolve() for path in args.paths]
        missing = [str(path) for path in paths if not path.is_file()]
        if missing:
            print(f"naming-gate: not a file: {', '.join(missing)}", file=sys.stderr)
            return 2
    else:
        paths = changed_paths(root)
    found = check(root, paths, args.whole)
    if not found:
        return 0
    print("=== naming ===")
    print("\n".join(found))
    print(
        "\nRename these by role. The procedure is in ~/.agents/skills/naming/SKILL.md"
    )
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
